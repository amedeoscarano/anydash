// Markdown rendering of rules. Deterministic: same input, same bytes.
export const HEADER = '<!-- Generated by scripts/build-references from rules/source. Do not edit. -->\n\n';
const one = (s) => String(s ?? '').replace(/\s+/g, ' ').trim();
const evidence = (r) => r.evidence.map((e) => `${e.portal} ${e.status}`).join(', ');

export function renderRule(r) {
  return [
    `### ${r.id} — ${one(r.title)}`,
    '',
    `**Rule:** ${one(r.rule)}`,
    '',
    `- Why: ${one(r.why)}`,
    `- Confidence: ${r.confidence} (source ${r.source}; ${evidence(r)})`,
    `- Applies when: ${one(r.applies_when)}`,
    `- Exceptions: ${one(r.exceptions)}`,
    `- Do: ${one(r.do)}`,
    `- Don't: ${one(r.dont)}`,
    `- Check (static): ${one(r.check_static)}`,
    `- Check (live): ${one(r.check_live)}`,
    '',
  ].join('\n');
}

function byArea(rules, areas) {
  return areas.map((a) => [a, rules.filter((r) => r.area === a)]).filter(([, rs]) => rs.length);
}

export function renderRulebook(rules, areas) {
  const groups = byArea(rules, areas);
  const count = (c) => rules.filter((r) => r.confidence === c).length;
  const toc = groups.map(([a, rs]) => `- [${a}](#${a}) (${rs.length})`).join('\n');
  const body = groups.map(([a, rs]) => `## ${a}\n\n${rs.map(renderRule).join('\n')}`).join('\n');
  return `${HEADER}# Rulebook\n\n${rules.length} rules: ${count('high')} high, ${count('medium')} medium, ${count('low')} low confidence.\nConfidence: high = seen or documented in all three reference portals, or stated by a public design system; medium = two of three; low = one, or inferred.\n\n${toc}\n\n${body}`;
}

export function renderSkillRules(skill, rules, areas) {
  const groups = byArea(rules, areas);
  const index = groups.flatMap(([, rs]) => rs.map((r) => `| ${r.id} | ${one(r.title)} | ${r.confidence} |`)).join('\n');
  const body = groups.map(([a, rs]) => `## ${a}\n\n${rs.map(renderRule).join('\n')}`).join('\n');
  return `${HEADER}# Rules for ${skill}\n\nAreas: ${areas.join(', ')}. Cite rules by ID in every decision and finding.\n\n| ID | Title | Confidence |\n|---|---|---|\n${index}\n\n${body}`;
}
